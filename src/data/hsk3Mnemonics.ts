/**
 * Trả về mẹo nhớ mặt chữ hoặc phân tích chiết tự cho từ bất kỳ
 */
export function getWordMnemonic(word: { hanzi: string; vietnamese?: string; pinyin?: string }): string {
  if (HSK3_MNEMONICS[word.hanzi]) {
    return HSK3_MNEMONICS[word.hanzi];
  }

  // Nếu là từ ghép, phân tích theo từng chữ cái
  const chars = Array.from(word.hanzi);
  const matchedCharNotes = chars
    .map((c) => HSK3_MNEMONICS[c] ? `• Chữ「${c}」: ${HSK3_MNEMONICS[c]}` : '')
    .filter(Boolean);

  if (matchedCharNotes.length > 0) {
    return matchedCharNotes.join('\n');
  }

  // Mẹo tự động dựa trên nghĩa và mặt chữ
  return `Nhìn sâu vào chữ Hán「${word.hanzi}」: Tập trung phân biệt từng nét viết và bộ thủ để ghi nhớ phản xạ đọc "${word.vietnamese || ''}".`;
}

